import { chromium } from "playwright";
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
await page.goto("http://localhost:3000/work/faculty-ops", { waitUntil: "networkidle" });
await page.waitForTimeout(600);
const fig = await page.$("figure:has(svg[aria-label*='functional index'])");
await fig.scrollIntoViewIfNeeded();
await page.waitForTimeout(300);
await fig.screenshot({ path: "/tmp/redesign-screenshots/faculty-diagram-desktop.png" });
console.log("saved");
await browser.close();
